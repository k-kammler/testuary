    assert [record["request_idx"] for record in requests] == [1, 2]
    assert [record["request_idx"] for record in transports] == [1, 2]
    for response, outbound in zip(requests, transports, strict=True):
        assert response["run"] == outbound["run"]
        assert response["slot"] == outbound["slot"] == 1
        assert response["logical_request_idx"] == outbound["logical_request_idx"] == 1
        assert outbound["sent_settings"]["protocol"] == protocol
